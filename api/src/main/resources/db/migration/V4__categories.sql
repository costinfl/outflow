-- Tier 1 (USER, from "apply to this merchant") and tier 4 (SEED keywords). Patterns match the merchant key:
-- MERCHANT = the whole key, KEYWORD = consecutive whole words anywhere in it.
CREATE TABLE category_rule (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES household (id),
    source       text   NOT NULL CHECK (source IN ('USER', 'SEED')),
    priority     integer NOT NULL DEFAULT 100,
    match_type   text   NOT NULL CHECK (match_type IN ('MERCHANT', 'KEYWORD')),
    pattern      text   NOT NULL CHECK (pattern <> '' AND pattern = upper(pattern)),
    category_id  bigint NOT NULL REFERENCES category (id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT category_rule_uq UNIQUE (household_id, source, match_type, pattern)
);

-- Tier 2: learned from the user's confirmations (written by CP2.3's recategorize endpoint).
ALTER TABLE merchant ADD COLUMN default_category_id bigint REFERENCES category (id);

ALTER TABLE transaction
    ADD COLUMN category_id bigint REFERENCES category (id),
    -- USER = set by hand on this transaction: automation never touches it again.
    ADD COLUMN category_source text CHECK (category_source IN ('USER', 'RULE', 'LEARNED', 'MCC', 'KEYWORD', 'SYSTEM')),
    ADD COLUMN category_confidence numeric(3, 2) CHECK (category_confidence BETWEEN 0 AND 1),
    ADD CONSTRAINT transaction_category_source_ck CHECK ((category_id IS NULL) = (category_source IS NULL));

CREATE INDEX transaction_category_idx ON transaction (category_id);

