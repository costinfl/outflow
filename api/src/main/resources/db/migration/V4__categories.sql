-- M2 / CP2.2: categories and resolution (DESIGN: Category resolution, Seed categories).
-- A transaction's category is an interpretation with its source; only automation-set categories are ever recomputed.

CREATE TABLE category (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  bigint REFERENCES category (id),
    code       text NOT NULL CHECK (code ~ '^[A-Z][A-Z_]*$'),
    name       text NOT NULL,
    -- SPEND counts towards "spent"; INCOME and TRANSFER never do (DESIGN: Home screen design rules).
    kind       text NOT NULL CHECK (kind IN ('SPEND', 'INCOME', 'TRANSFER')),
    sort_order integer NOT NULL DEFAULT 0,
    CONSTRAINT category_code_uq UNIQUE (code)
);

