-- M1 / CP1.1: import and identity schema (DESIGN: Data model, Transaction identity and idempotency).
-- Facts (raw_row, transaction) are immutable or append-only. Interpretations (merchant, category, transfer pair,
-- subscription) get their own columns/tables in later migrations, alongside the tables they reference.

CREATE TABLE household (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL
);

CREATE TABLE app_user (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES household (id),
    email        text UNIQUE
);

